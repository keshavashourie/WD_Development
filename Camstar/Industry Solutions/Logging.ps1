# Write to log file and error stream
function Write-LogError([string] $message) 
{
    $infoLine = Write-LineToFile($message)
	
    Write-Error $message
}

# Write to log file and warning stream
function Write-LogWarning([string] $message) 
{
    $warningLine = Write-LineToFile($message)
	
    Write-Warning $message
}

# Write to log file and information stream
function Write-LogInfo([string] $message) 
{
    $errorLine = Write-LineToFile($message)
	
    Write-Information $message
}

function Write-LineToFile([string] $message) 
{
    $stamp = (Get-Date).toString("MM/dd/yyyy HH:mm:ss")
    $line = "$stamp $message"
    $line | out-file -Filepath $logFile -append
    return $line
}
