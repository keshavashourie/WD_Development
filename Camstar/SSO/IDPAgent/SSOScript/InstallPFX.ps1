# Define file paths and certificate details
#Configure this path according to the system
$camstarPath = $ENV:CamstarInstall
$SSODirPath = Join-Path $camstarPath "SSO"
#File name
$CertificateFile = "$SSODirPath\IDPAgent\app_data\Certificates\IdpSaml.crt" 
#password configured in Management Studio
$Password =  ConvertTo-SecureString -String "localhost" -Force -AsPlainText 
$IdpAgentFolderPath = "$SSODirPath\IDPAgent\app_data\jwt\cert.pfx"
 
# Self-elevate the script if required
if (-Not ([Security.Principal.WindowsPrincipal] [Security.Principal.WindowsIdentity]::GetCurrent()).IsInRole([Security.Principal.WindowsBuiltInRole] 'Administrator')) {
    if ([int](Get-CimInstance -Class Win32_OperatingSystem | Select-Object -ExpandProperty BuildNumber) -ge 6000) {
        $CommandLine = "-File `"" + $MyInvocation.MyCommand.Path + "`" " + $MyInvocation.UnboundArguments
        Start-Process -FilePath PowerShell.exe -Verb Runas -ArgumentList $CommandLine
        Exit
    }
}

# Create folder structure
try {
		New-Item -ItemType Directory -Path "$SSODirPath\IDPAgent\app_data" -Force | Out-Null
		New-Item -ItemType Directory -Path "$SSODirPath\IDPAgent\app_data\Certificates" -Force | Out-Null
		New-Item -ItemType Directory -Path "$SSODirPath\IDPAgent\app_data\jwt" -Force | Out-Null
}
catch {
	if ($_.Exception.Message -like "*already exists*") {
		Write-Host "The 'app_data' directory already exists. Skipping folder creation."
		Write-Host
	}
	else {
		Write-Host "An error occurred while creating the folder structure: $($_.Exception.Message)"
		Exit
	}
}
 
# Create certificate
$cert = New-SelfSignedCertificate -FriendlyName "OpcenterSSL" -DnsName localhost,127.0.0.1,myservername,*.siemensesmc.com -CertStoreLocation "cert:\LocalMachine\My" -KeyUsage DigitalSignature,KeyEncipherment,DataEncipherment -KeyAlgorithm RSA -HashAlgorithm SHA256 -KeyLength 2048 -KeyUsageProperty All -Provider "Microsoft Enhanced RSA and AES Cryptographic Provider" -NotAfter "9999-12-30 23:59:59"
Export-Certificate -Cert $cert -FilePath $CertificateFile

Export-PfxCertificate -Cert $cert -FilePath $IdpAgentFolderPath -Password $Password
